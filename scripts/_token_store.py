"""Private, revisioned SQLite persistence for local token economics."""
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
import fcntl
import json
import os
from pathlib import Path
import re
import sqlite3
import stat
import time

SCHEMA_VERSION = 1
MARKER = 'Generated by 100xprism token economics'
DIAGNOSTIC_LIMIT = 1000


def _canonical_root(root):
    raw=Path(root).absolute()
    if raw.is_symlink() or raw.parent.is_symlink(): raise ValueError('token economics root is a symlink')
    return raw.resolve()


def _contained(root, target, allow_link=False):
    root=_canonical_root(root)
    target=Path(target)
    if (not target.is_absolute() or '..' in target.parts or target == root
            or not target.is_relative_to(root)):
        raise ValueError('artifact escapes token economics root')
    if root.is_symlink() or root.parent.is_symlink():
        raise ValueError('token economics root is a symlink')
    current=root
    pieces=target.relative_to(root).parts
    for index,piece in enumerate(pieces):
        current=current/piece
        if current.is_symlink() and not (allow_link and index==len(pieces)-1):
            raise ValueError('artifact symlink escape')
    return target


def load_manifest(root):
    """Validate the shared JS/Python ownership contract without modifying it."""
    root=_canonical_root(root)
    manifest_path=root.parent/'token-economics-manifest.json'
    if manifest_path.is_symlink(): raise ValueError('ownership manifest is a symlink')
    manifest=json.loads(manifest_path.read_text())
    if (manifest.get('schema')!=1 or manifest.get('marker')!=MARKER
            or manifest.get('root')!=str(root) or not isinstance(manifest.get('artifacts'),list)):
        raise ValueError('invalid token economics ownership manifest')
    kinds={'database','sidecar','generation','file','symlink','directory'}
    for entry in manifest['artifacts']:
        if not isinstance(entry,dict) or entry.get('kind') not in kinds:
            raise ValueError('invalid artifact kind')
        target=_contained(root,entry.get('path',''),entry['kind']=='symlink')
        if entry['kind']=='sidecar' and not any(d['kind']=='database' and str(target) in (d['path']+'-wal',d['path']+'-shm') for d in manifest['artifacts']):
            raise ValueError('sidecar has no owned database')
    return manifest


def _register_artifact_locked(root, path, kind='file'):
    """Register before creating; only an existing validated manifest grants ownership."""
    root=_canonical_root(root)
    manifest_path=root.parent/'token-economics-manifest.json'
    manifest=load_manifest(root)
    target=_contained(root,Path(path).absolute(),kind=='symlink')
    entries=[entry for entry in manifest['artifacts'] if entry['path']==str(target)]
    if entries:
        if entries[0]['kind']!=kind: raise ValueError('artifact kind changed')
        return str(target)
    if target.exists() or target.is_symlink(): raise ValueError('refusing foreign artifact')
    if kind=='sidecar' and not any(d['kind']=='database' and str(target) in (d['path']+'-wal',d['path']+'-shm') for d in manifest['artifacts']):
        raise ValueError('sidecar has no owned database')
    manifest['artifacts'].append({'path':str(target),'kind':kind})
    temp=_contained(root,root/'manifest-next.json')
    if not any(e['path']==str(temp) and e['kind']=='file' for e in manifest['artifacts']):
        raise ValueError('manifest replacement path is not registered')
    if temp.exists():
        info=temp.stat()
        if not stat.S_ISREG(info.st_mode) or info.st_uid!=os.getuid() or info.st_mode & 0o077:
            raise ValueError('manifest replacement path is not private and owned')
    fd=os.open(temp,os.O_WRONLY|os.O_CREAT|os.O_TRUNC,0o600)
    with os.fdopen(fd,'w') as fh:
        json.dump(manifest,fh,indent=2)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(temp,manifest_path)
    return str(target)


def register_artifact(root,path,kind='file'):
    root=_canonical_root(root)
    lock=_contained(root,root/'manifest.lock')
    manifest=load_manifest(root)
    if not any(e['path']==str(lock) and e['kind']=='file' for e in manifest['artifacts']):
        raise ValueError('manifest lock is not registered')
    fd=os.open(lock,os.O_CREAT|os.O_RDWR,0o600)
    try:
        fcntl.flock(fd,fcntl.LOCK_EX)
        return _register_artifact_locked(root,path,kind)
    finally: os.close(fd)


def content_timestamp(value):
    try:
        if isinstance(value,(int,float)) and not isinstance(value,bool):
            if value>1e12: value/=1000
            moment=datetime.fromtimestamp(value,timezone.utc)
        elif isinstance(value,str):
            moment=datetime.fromisoformat(value.replace('Z','+00:00'))
            if moment.tzinfo is None: moment=moment.replace(tzinfo=timezone.utc)
            moment=moment.astimezone(timezone.utc)
        else: return None
        return moment.strftime('%Y-%m-%dT%H:%M:%S.%fZ')
    except (ValueError,OverflowError,OSError): return None


class TokenStore:
    def __init__(self, db_path):
        self.path = str(Path(db_path).absolute())
        self.conn = None
        path = Path(self.path)
        if any(Path(self.path+suffix).is_symlink() for suffix in ('','-wal','-shm')):
            raise ValueError('database or sidecar must not be a symlink')
        self.root=next((p for p in path.parents if p.name=='token-economics'),path.parent.parent)
        # Probe in read-only mode before any journal/permission mutation.
        if path.exists():
            probe = sqlite3.connect(path.as_uri() + '?mode=ro', uri=True)
            try:
                version=probe.execute('PRAGMA user_version').fetchone()[0]
                if version > SCHEMA_VERSION:
                    raise ValueError('unsupported future token economics schema')
                if version==0 and probe.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchone():
                    raise ValueError('foreign SQLite schema')
                if version==SCHEMA_VERSION:
                    for table in ('metadata','source_files','source_locations','session_summaries','scan_runs','dashboard_snapshots','session_contributions'):
                        probe.execute('SELECT * FROM '+table+' LIMIT 0')
            finally: probe.close()
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(path.parent, 0o700)
        old_umask = os.umask(0o077)
        try:
            self.conn = sqlite3.connect(self.path, timeout=10)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute('PRAGMA foreign_keys=ON')
            self.conn.execute('PRAGMA busy_timeout=10000')
            self._migrate()
            self.conn.execute('PRAGMA journal_mode=WAL')
            self.conn.execute('PRAGMA synchronous=FULL')
        finally: os.umask(old_umask)
        self._permissions()

    def _migrate(self):
        version = self.conn.execute('PRAGMA user_version').fetchone()[0]
        if version == SCHEMA_VERSION: return
        # Sequential migrations: schema zero is the only released predecessor.
        with self.transaction():
            statements = [
                'CREATE TABLE metadata (key TEXT PRIMARY KEY,value TEXT NOT NULL)',
                '''CREATE TABLE source_locations(id INTEGER PRIMARY KEY,tool TEXT NOT NULL,root_path TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'never_scanned',committed_status TEXT NOT NULL DEFAULT 'never_scanned',
                    last_scan_started_at REAL,last_scan_finished_at REAL,last_full_scan_at REAL,
                    file_count INTEGER DEFAULT 0,present_file_count INTEGER DEFAULT 0,last_error TEXT,
                    UNIQUE(tool,root_path))''',
                '''CREATE TABLE source_files(id INTEGER PRIMARY KEY,location_id INTEGER NOT NULL REFERENCES source_locations(id),
                    path TEXT NOT NULL,device INTEGER,inode INTEGER,size INTEGER,mtime_ns INTEGER,
                    parsed_offset INTEGER NOT NULL DEFAULT 0,tail_anchor TEXT,partial_digest TEXT,partial_length INTEGER DEFAULT 0,
                    integrity_cursor INTEGER DEFAULT 0,parser_version TEXT,parser_state_json TEXT DEFAULT '{}',session_key TEXT,summary_json TEXT,contribution_key TEXT,
                    present INTEGER DEFAULT 1,last_seen_run_id INTEGER,last_error TEXT,observed_signature_json TEXT,
                    content_offset INTEGER DEFAULT 0,content_parser_version TEXT,content_state_json TEXT DEFAULT '{}',UNIQUE(location_id,path))''',
                '''CREATE TABLE source_file_blocks(file_id INTEGER NOT NULL REFERENCES source_files(id) ON DELETE CASCADE,
                    block_index INTEGER NOT NULL,digest TEXT NOT NULL,length INTEGER NOT NULL,PRIMARY KEY(file_id,block_index))''',
                '''CREATE TABLE session_contributions(contribution_key TEXT PRIMARY KEY,session_key TEXT NOT NULL,
                    tool TEXT NOT NULL,summary_json TEXT NOT NULL,updated_at REAL NOT NULL)''',
                '''CREATE TABLE session_summaries(session_key TEXT PRIMARY KEY,tool TEXT NOT NULL,project TEXT,
                    summary_json TEXT NOT NULL,updated_at REAL NOT NULL)''',
                '''CREATE TABLE scan_runs(id INTEGER PRIMARY KEY,status TEXT,started_at REAL,finished_at REAL,
                    locations_inspected INTEGER DEFAULT 0,files_inspected INTEGER DEFAULT 0,files_parsed INTEGER DEFAULT 0,
                    bytes_parsed INTEGER DEFAULT 0,sessions_updated INTEGER DEFAULT 0,last_error TEXT)''',
                '''CREATE TABLE dashboard_snapshots(id INTEGER PRIMARY KEY,created_at REAL NOT NULL,run_id INTEGER,
                    revision INTEGER NOT NULL,payload_json TEXT NOT NULL)''',
            ]
            for statement in statements: self.conn.execute(statement)
            for key, value in [('snapshot_input_revision','0'),('snapshot_revision','-1'),('search_enabled','0'),
                               ('value_context','[{},{}]'),('value_store','{}'),('value_format_version','1'),
                               ('integrity_due','0'),('integrity_verified_at','null'),('integrity_cycle_pending','[]')]:
                self.conn.execute('INSERT INTO metadata VALUES (?,?)',(key,value))
            self.conn.execute('PRAGMA user_version=1')

    @contextmanager
    def transaction(self):
        try:
            self.conn.execute('BEGIN IMMEDIATE')
            yield
            self.conn.commit()
        except BaseException:
            self.conn.rollback()
            raise
        finally: self._permissions()

    def _permissions(self):
        for suffix in ('','-wal','-shm'):
            p = Path(self.path+suffix)
            if p.exists(): os.chmod(p,0o600)

    def get_meta(self,key,default=None):
        row=self.conn.execute('SELECT value FROM metadata WHERE key=?',(key,)).fetchone()
        return json.loads(row[0]) if row else default

    def set_meta(self,key,value):
        self.conn.execute('INSERT INTO metadata VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',
                          (key,json.dumps(value,separators=(',',':'))))

    def bump_revision(self):
        self.set_meta('snapshot_input_revision',self.get_meta('snapshot_input_revision',0)+1)

    @property
    def revisions(self):
        return self.get_meta('snapshot_input_revision'),self.get_meta('snapshot_revision')

    def latest_snapshot(self):
        # The prior complete payload remains usable if the latest JSON was corrupted.
        for row in self.conn.execute('SELECT payload_json FROM dashboard_snapshots ORDER BY id DESC LIMIT 2'):
            try: return json.loads(row[0])
            except (TypeError,ValueError): continue
        return None

    def publish_snapshot(self,payload,run_id=None,expected_revision=None):
        encoded=json.dumps(payload,allow_nan=False,separators=(',',':'))
        with self.transaction():
            revision=self.revisions[0]
            if expected_revision is not None and expected_revision != revision:
                raise RuntimeError('snapshot inputs changed during aggregation')
            self.conn.execute('INSERT INTO dashboard_snapshots(created_at,run_id,revision,payload_json) VALUES (?,?,?,?)',
                              (time.time(),run_id,revision,encoded))
            self.conn.execute('DELETE FROM dashboard_snapshots WHERE id NOT IN (SELECT id FROM dashboard_snapshots ORDER BY id DESC LIMIT 2)')
            self.set_meta('snapshot_revision',revision)

    def summaries(self):
        rows=[]
        for row in self.conn.execute('SELECT session_key,summary_json FROM session_summaries ORDER BY session_key'):
            summary=json.loads(row['summary_json'])
            summary['historical']=not bool(self.conn.execute('SELECT 1 FROM source_files WHERE session_key=? AND present=1 LIMIT 1',(row['session_key'],)).fetchone())
            rows.append(summary)
        return rows

    def value_context(self):
        return tuple(self.get_meta('value_context',[{},{}])),self.get_meta('value_store',{})

    def save_value_context(self,context,value_store):
        with self.transaction():
            if list(context) != self.get_meta('value_context') or value_store != self.get_meta('value_store'):
                self.set_meta('value_context',list(context))
                self.set_meta('value_store',value_store)
                self.bump_revision()

    def status(self):
        locations=[dict(row) for row in self.conn.execute('SELECT * FROM source_locations ORDER BY tool,root_path')]
        run=self.conn.execute('SELECT * FROM scan_runs ORDER BY id DESC LIMIT 1').fetchone()
        content=self.conn.execute('SELECT count(*) total,sum(content_offset>=size) complete FROM source_files WHERE present=1').fetchone()
        return {'locations':locations,'run':dict(run) if run else None,
                'snapshot_input_revision':self.revisions[0],'snapshot_revision':self.revisions[1],
                'search_enabled':bool(self.get_meta('search_enabled',False)) and not self.search_fenced(),
                'content_backfill':{'total':content['total'],'complete':content['complete'] or 0},
                'integrity_verified_at':self.get_meta('integrity_verified_at'),
                'integrity_due':self.get_meta('integrity_due')}

    def recover_runs(self):
        with self.transaction():
            self.conn.execute("UPDATE scan_runs SET status='abandoned',finished_at=? WHERE status='running'",(time.time(),))
            self.conn.execute("UPDATE source_locations SET status=committed_status WHERE status='scanning'")
            self.set_meta('lease',None)

    def start_run(self):
        self.recover_runs()
        with self.transaction():
            cur=self.conn.execute("INSERT INTO scan_runs(status,started_at) VALUES('running',?)",(time.time(),))
            self.set_meta('lease',{'pid':os.getpid(),'run_id':cur.lastrowid,'expires':time.time()+300})
            self.conn.execute('DELETE FROM scan_runs WHERE id NOT IN (SELECT id FROM scan_runs ORDER BY id DESC LIMIT ?)',(DIAGNOSTIC_LIMIT,))
            return cur.lastrowid

    def finish_run(self,run_id,status='complete',error=None,**counts):
        columns=('locations_inspected','files_inspected','files_parsed','bytes_parsed','sessions_updated')
        with self.transaction():
            self.conn.execute('UPDATE scan_runs SET status=?,finished_at=?,last_error=?,'+
                              ','.join(c+'=?' for c in columns)+' WHERE id=?',
                              (status,time.time(),error,*[counts.get(c,0) for c in columns],run_id))
            self.set_meta('lease',None)

    def enable_search(self):
        with self.transaction():
            self.conn.execute('''CREATE TABLE IF NOT EXISTS session_content(id INTEGER PRIMARY KEY,session_key TEXT,
                tool TEXT,project TEXT,role TEXT,timestamp TEXT,sequence INTEGER,text TEXT,source_key TEXT,
                UNIQUE(session_key,source_key,sequence,role))''')
            self.conn.execute("CREATE VIRTUAL TABLE IF NOT EXISTS session_content_fts USING fts5(text, content='session_content',content_rowid='id')")
            self.set_meta('search_enabled',True)
            self.bump_revision()

    def put_content(self,key,tool,project,rows,source_key=''):
        if not self.get_meta('search_enabled'): return
        own_transaction=not self.conn.in_transaction
        if own_transaction: self.conn.execute('BEGIN IMMEDIATE')
        mutated=False
        for row in rows:
            if row.get('role') not in ('user','assistant') or not isinstance(row.get('text'),str): continue
            cur=self.conn.execute('INSERT OR IGNORE INTO session_content(session_key,tool,project,role,timestamp,sequence,text,source_key) VALUES(?,?,?,?,?,?,?,?)',
                                  (key,tool,project,row['role'],content_timestamp(row.get('timestamp')),row.get('sequence',0),row['text'],source_key))
            if cur.rowcount:
                self.conn.execute('INSERT INTO session_content_fts(rowid,text) VALUES(?,?)',(cur.lastrowid,row['text']))
                mutated=True
        if mutated: self.bump_revision()
        if own_transaction: self.conn.commit()
        self._permissions()

    def clear_content(self,key,source_key=None):
        if not self.get_meta('search_enabled'): return
        where='session_key=?'+(' AND source_key=?' if source_key is not None else '')
        params=(key,source_key) if source_key is not None else (key,)
        for row in self.conn.execute('SELECT id,text FROM session_content WHERE '+where,params).fetchall():
            self.conn.execute("INSERT INTO session_content_fts(session_content_fts,rowid,text) VALUES('delete',?,?)",tuple(row))
        self.conn.execute('DELETE FROM session_content WHERE '+where,params)

    def disable_search(self):
        # Consent off is independently durable, even if secure cleanup subsequently fails.
        self.conn.commit()
        with self.transaction():
            self.set_meta('search_enabled',False)
            self.bump_revision()
        self.conn.execute('PRAGMA secure_delete=ON')
        with self.transaction():
            self.conn.execute('DROP TABLE IF EXISTS session_content_fts')
            self.conn.execute('DROP TABLE IF EXISTS session_content')
            self.conn.execute('UPDATE source_files SET content_offset=0,content_parser_version=NULL')
        self.checkpoint()
        self.conn.execute('VACUUM')
        self.checkpoint()
        self.close()
        for suffix in ('-wal','-shm'):
            path=Path(self.path+suffix)
            if path.exists():
                if path.stat().st_size: raise RuntimeError('content cleanup left nonempty SQLite sidecar')
                path.unlink()

    def search_fenced(self):
        return (self.root/'content-search-disabled').exists()

    def search(self,query,tool=None,project=None,role=None,date_from=None,date_to=None,limit=20):
        if self.conn is None or self.search_fenced() or not self.get_meta('search_enabled'): return []
        if not isinstance(query,str) or not query.strip() or len(query)>512: return []
        limit=max(1,min(int(limit),100))
        where=['session_content_fts MATCH ?']
        params=[query]
        try:
            if date_from:
                lower=datetime.strptime(date_from,'%Y-%m-%d')
                where.append('c.timestamp>=?')
                params.append(lower.strftime('%Y-%m-%dT00:00:00'))
            if date_to:
                upper=datetime.strptime(date_to,'%Y-%m-%d')+timedelta(days=1)
                where.append('c.timestamp<?')
                params.append(upper.strftime('%Y-%m-%dT00:00:00'))
        except (ValueError,TypeError,OverflowError): return []
        for column,value,op in [('tool',tool,'='),('project',project,'='),('role',role,'=')]:
            if value is not None:
                where.append('c.'+column+op+'?')
                params.append(value)
        try:
            result=self.conn.execute('SELECT c.*,highlight(session_content_fts,0,char(1),char(2)) highlighted FROM session_content_fts JOIN session_content c ON c.id=session_content_fts.rowid WHERE '+
                                     ' AND '.join(where)+' ORDER BY bm25(session_content_fts) LIMIT ?',(*params,limit)).fetchall()
        except sqlite3.OperationalError: return []
        out=[]
        for row in result:
            highlighted=row['highlighted']
            # Return plain structured segments; HTML is never generated from transcript text.
            first=highlighted.find('\x01')
            excerpt=highlighted[max(0,first-100) if first>=0 else 0:][:600]
            parts=re.split('(\x01|\x02)',excerpt)
            matched=False
            segments=[]
            for part in parts:
                if part=='\x01': matched=True
                elif part=='\x02': matched=False
                elif part: segments.append({'text':part,'matched':matched})
            item={k:row[k] for k in ('session_key','tool','project','role','timestamp','sequence')}
            item['segments']=segments
            out.append(item)
        return out

    def checkpoint(self):
        self.conn.commit()
        busy,log,done=self.conn.execute('PRAGMA wal_checkpoint(TRUNCATE)').fetchone()
        if busy or log!=done: raise RuntimeError('SQLite readers prevented checkpoint')

    def validate(self):
        if self.conn.execute('PRAGMA integrity_check').fetchone()[0]!='ok':
            raise ValueError('token economics database integrity check failed')
        if self.conn.execute('PRAGMA user_version').fetchone()[0]!=SCHEMA_VERSION:
            raise ValueError('unsupported token economics schema')
        for table in ('metadata','source_files','source_locations','session_summaries','scan_runs','dashboard_snapshots'):
            self.conn.execute('SELECT * FROM '+table+' LIMIT 0')
        self.checkpoint()

    def close(self):
        if self.conn is not None:
            self.conn.close()
            self.conn=None

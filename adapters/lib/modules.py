#!/usr/bin/env python3
"""Single parser for modules/<slug>/SKILL.md.

Used by all adapters. Outputs JSON to stdout with one of these subcommands:

  list                       — full manifest (all modules, sorted by category/name)
  detect-profiles <dir>      — JSON: profiles a project looks like + resulting split
  emit-cursor <project_dir>  — write .cursor/rules/<slug>.mdc per module
  emit-codex <project_dir>   — write Codex-native AGENTS.md, repo skills, hooks
  emit-pi <project_dir>      — write retention-filtered .pi/skills (+ prompts, catalog)
  emit-pi-package            — write filtered pi/skills for `pi install` (repo root)
  emit-claude-code           — write ~/.claude/skills/<slug>/* + ~/.claude/commands/<slug>.md
  emit-hermes                — write ~/.hermes/skills/100xprism/<slug>/SKILL.md (Hermes/OpenClaw)
  emit-hooks [--sync]        — idempotently merge first-party hooks into
                               ~/.claude/settings.json from hooks/hooks.manifest.json.
                               Each hook is enabled per its manifest `default`, overridable
                               by its `toggle_env` env var (1/true=on, 0/false=off).
                               --sync only refreshes hooks already present (used on update).
"""
from __future__ import annotations

import json
import os
import shlex
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MODULES_DIR = REPO / "modules"
CODEX_HOOK_TEMPLATE = REPO / "adapters" / "templates" / "codex-run-hook.py"

# Markers + manifest let `emit-claude-code` prune ONLY 100xprism's own artifacts
# (never the user's hand-authored skills/commands) when a module is removed or
# merged upstream. See cmd_emit_claude_code.
GENERATED_MARKER = ".100xprism-generated"
ALIAS_MARKER = "<!-- 100xprism generated alias — regenerate, do not edit -->"
MANIFEST_NAME = ".100xprism-manifest.json"

# Cursor .mdc rules carry their marker in an HTML comment on line 7, below the
# frontmatter block. Both this emitter and the JS port in lib/adapters/windows.js
# must scan at least that far or pruning silently matches nothing.
CURSOR_MARKER = "generated by 100xprism"
CURSOR_MARKER_LINES = 10

# Modules removed in past releases. Cleaned up on update even for installs whose
# skills predate the manifest/marker (so they carry neither). Safe to trim once
# installs have cycled through a manifest-aware update.
REMOVED_MODULES = {"systems-architect", "conversion-copy"}

# Central model-routing map. Modules declare a bare alias (`model: haiku`) in
# frontmatter. Claude Code reads that alias natively and auto-resolves it to the
# latest version — so the alias is emitted verbatim there (see cmd_emit_claude_code,
# which copies frontmatter as-is). Every other adapter picks its own (often
# non-Claude) model, so they receive a vendor-neutral reasoning-tier hint instead of
# a Claude model name. `id`/`label` are the single source of truth for the deferred
# slash-command / documentation work; the emitters in this pass use `tier_hint`.
MODEL_ALIASES = {
    "haiku":  {"id": "claude-haiku-4-5",  "label": "Claude Haiku 4.5",  "tier_hint": "fast / low-cost (mechanical task)"},
    "sonnet": {"id": "claude-sonnet-5",   "label": "Claude Sonnet 5",   "tier_hint": "balanced (moderate reasoning)"},
    "opus":   {"id": "claude-opus-5",     "label": "Claude Opus 5",     "tier_hint": "most capable (deep reasoning)"},
}


def tier_annotation(model: str) -> str:
    """Vendor-neutral routing hint for non-Claude adapters. '' for unknown/empty alias."""
    info = MODEL_ALIASES.get(model.strip())
    return f"_Suggested model tier: {info['tier_hint']}_" if info else ""


# ── Retention classes ────────────────────────────────────────────────────────
# Every module's description is re-sent on every turn once it is installed as a
# real skill, so *installing* a module has a standing token cost while its body
# is free until invoked. Retention decides which modules earn that standing cost.
#
#   must     — deterministic machinery or house policy a model will not
#              reproduce unprompted (what commands `gate` runs, the order
#              `release` runs them in, the handoff protocol `pair-loop` speaks).
#              Installed everywhere, always.
#   profile  — earns its place only in repos of a matching kind.
#   resolver — general expertise a capable model already has. Never installed as
#              a skill; appears as one row in the generated resolver catalog and
#              is loaded by path on demand.
#
# A module may override the derived class with `retention:` in its frontmatter.
RETENTION_CLASSES = ("must", "profile", "resolver")

MUST_HAVE = {
    "gate", "commit", "push", "branch", "pr", "release",
    "test", "lint", "security", "docs", "eval", "pair-loop",
}

# Categories whose modules are advice-shaped by default. Overridden per module by
# `retention:`, and never applied to a module that owns a slash command — the user
# can type that command, so the skill has to exist.
RESOLVER_CATEGORIES = {"marketing", "design"}

# Which repos a module earns its standing cost in. Derived from category unless a
# module declares `profiles:`. "core" is implicitly active in every project.
CATEGORY_PROFILES = {
    "lifecycle": ["core"],
    "quality": ["core"],
    "engineering": ["code"],
    "docs": ["code"],
    "data": ["data"],
    "design": ["design"],
    "marketing": ["growth"],
}
KNOWN_PROFILES = ("core", "code", "data", "design", "growth")


def retention_of(fm: dict, slug: str, category: str, slash_command: str) -> str:
    """Derived retention class, overridable by frontmatter `retention:`."""
    declared = fm.get("retention", "").strip()
    if declared in RETENTION_CLASSES:
        return declared
    if slug in MUST_HAVE:
        return "must"
    # An invocable command must resolve to a real skill, whatever its category.
    if slash_command:
        return "profile"
    if category in RESOLVER_CATEGORIES:
        return "resolver"
    return "profile"


def profiles_of(fm: dict, category: str) -> list[str]:
    """Derived profile list, overridable by frontmatter `profiles: a, b`."""
    declared = [p.strip() for p in fm.get("profiles", "").replace(",", " ").split() if p.strip()]
    if declared:
        return declared
    return list(CATEGORY_PROFILES.get(category, ["core"]))


def short_description(desc: str) -> str:
    """First sentence of a description, capped at 140 chars — for tight rule triggering."""
    d = desc.split(". ", 1)[0]
    if len(d) > 140:
        d = d[:137] + "..."
    return d


# Hermes/OpenClaw renders only the first ~57 chars of a skill description in its
# always-on system-prompt index (longer strings are silently truncated with '...',
# destroying the trigger signal a model uses to decide whether to load the skill).
# See adapters/lib/modules.py cmd_emit_hermes and docs/hermes-adapter.md for the
# full rationale. A module can hand-tune this with `hermes_description:` in its
# frontmatter when the derived truncation reads awkwardly.
HERMES_DESC_MAX = 57


def hermes_description(fm: dict, desc: str) -> str:
    """One-sentence, <=57-char, trigger-first description for the Hermes index.

    Precedence: explicit `hermes_description:` frontmatter override, else the
    module's first sentence (short_description), hard-truncated at a word
    boundary and re-punctuated if it still doesn't fit.
    """
    override = fm.get("hermes_description", "").strip()
    if override:
        d = override
    else:
        d = short_description(desc)

    if not d.endswith("."):
        d = d + "."
    if len(d) <= HERMES_DESC_MAX:
        return d

    # Hard truncate at a word boundary inside the budget, minus room for the
    # trailing period so the result never exceeds HERMES_DESC_MAX.
    budget = HERMES_DESC_MAX - 1
    truncated = d[:budget].rsplit(" ", 1)[0].rstrip(".,;: ")
    if not truncated:
        truncated = d[:budget].rstrip(".,;: ")
    return truncated + "."


def render_command_alias(fm: dict, slug: str, body: str) -> str:
    """Slash-command alias that mirrors the skill's routing/guardrails in frontmatter.

    Commands and skills share a frontmatter schema, so the alias carries description,
    model routing, and allowed-tools instead of dropping them. argument-hint is emitted
    generically only when the body actually consumes positional input.
    """
    lines = ["---", f"description: {short_description(fm.get('description', ''))}"]
    model = fm.get("model", "").strip()
    if model:
        lines.append(f"model: {model}")
    allowed = fm.get("allowed-tools", "").strip()
    if allowed:
        lines.append(f"allowed-tools: {allowed}")
    if "$ARGUMENTS" in body or "$1" in body:
        lines.append("argument-hint: [arguments]")
    lines += ["---", "", ALIAS_MARKER, "", f"Use the `{fm.get('name', slug)}` skill.", "", "$ARGUMENTS", ""]
    return "\n".join(lines)


def split_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    fm_block = text[4:end]
    body = text[end + 5 :]
    fm: dict[str, str] = {}
    current_key: str | None = None
    for line in fm_block.splitlines():
        if not line.strip():
            continue
        if line.startswith(" ") and current_key:
            fm[current_key] = (fm[current_key] + " " + line.strip()).strip()
            continue
        if ":" in line:
            key, _, val = line.partition(":")
            current_key = key.strip()
            fm[current_key] = val.strip()
    return fm, body


def list_modules() -> list[dict]:
    out: list[dict] = []
    for skill_md in sorted(MODULES_DIR.glob("*/SKILL.md")):
        fm, body = split_frontmatter(skill_md.read_text())
        category = fm.get("category", "uncategorized")
        slash_command = fm.get("slash_command", "")
        slug = skill_md.parent.name
        out.append({
            "slug": slug,
            "name": fm.get("name", slug),
            "description": fm.get("description", ""),
            "category": category,
            "tier": fm.get("tier", "on-demand"),
            "retention": retention_of(fm, slug, category, slash_command),
            "profiles": profiles_of(fm, category),
            "slash_command": slash_command,
            "allowed_tools": fm.get("allowed-tools", ""),
            "model": fm.get("model", ""),
            "body": body,
            "dir": str(skill_md.parent),
        })
    out.sort(key=lambda m: (m["tier"] != "core", m["category"], m["slug"]))
    return out


# ── Per-project profile resolution ───────────────────────────────────────────
# Filtering is OFF unless a project opts in, so an emit into a bare directory
# behaves exactly as it did before profiles existed. `100xprism init` and
# `100xprism slim` write the config that turns it on; `profiles: ["all"]` in that
# config turns it back off again without deleting the file.
PROJECT_CONFIG = ".100xprism.json"

# Ordered so the first match wins for reporting purposes; a repo can match several.
PROFILE_MARKERS = {
    "code": [
        "package.json", "pyproject.toml", "setup.py", "requirements.txt", "go.mod",
        "Cargo.toml", "pom.xml", "build.gradle", "Gemfile", "composer.json",
        "tsconfig.json", "CMakeLists.txt",
    ],
    "data": [
        "terraform", "dbt_project.yml", "docker-compose.yml", "docker-compose.yaml",
        "migrations", "alembic.ini", "Dockerfile",
    ],
    "design": [
        "tailwind.config.js", "tailwind.config.ts", "tailwind.config.cjs",
        ".storybook", "components", "src/components",
    ],
    "growth": [
        "content", "posts", "_posts", "blog", "marketing", "landing",
        "next-sitemap.config.js", "public/robots.txt",
    ],
}


def detect_profiles(project_dir: str | Path) -> list[str]:
    """Best-effort repo classification. Always includes 'core'.

    A repo with no recognisable marker at all gets 'growth' as well as 'core' —
    a bare content/docs directory is the case that would otherwise silently lose
    every module it might actually want.
    """
    project = Path(project_dir)
    found = ["core"]
    for profile in ("code", "data", "design", "growth"):
        if any((project / marker).exists() for marker in PROFILE_MARKERS[profile]):
            found.append(profile)
    if found == ["core"]:
        found.append("growth")
    return found


def read_project_config(project_dir: str | Path) -> dict:
    try:
        return json.loads((Path(project_dir) / PROJECT_CONFIG).read_text())
    except (OSError, ValueError):
        return {}


def active_profiles(project_dir: str | Path) -> list[str] | None:
    """Profiles to filter by; [] means must-only and None explicitly means all.

    Precedence: PRISM_PROFILES env override → project config → lean default. Both
    the env var and the config accept "all" as an explicit opt-out of filtering.
    """
    env = os.environ.get("PRISM_PROFILES", "").strip()
    if env:
        vals = [p.strip() for p in env.replace(",", " ").split() if p.strip()]
        if "all" in vals:
            return None
        return sorted(set(vals) | {"core"})

    cfg = read_project_config(project_dir).get("profiles")
    if not cfg:
        return []
    if isinstance(cfg, str):
        cfg = [cfg]
    if "all" in cfg:
        return None
    return sorted({str(p).strip() for p in cfg if str(p).strip()} | {"core"})


def select_modules(modules: list[dict], profiles: list[str] | None) -> tuple[list[dict], list[dict]]:
    """Split into (installed as real artifacts, resolver-only).

    With no active profiles this keeps every non-resolver module, which is what
    every pre-profiles caller got. `must` modules ignore profiles by definition.
    """
    keep: list[dict] = []
    catalog: list[dict] = []
    for m in modules:
        if m["retention"] == "resolver":
            catalog.append(m)
        elif m["retention"] == "must" or profiles is None:
            keep.append(m)
        elif set(m["profiles"]) & set(profiles):
            keep.append(m)
        else:
            catalog.append(m)
    return keep, catalog


CATEGORY_ORDER = [
    "lifecycle", "quality", "engineering", "data", "design", "docs", "marketing", "uncategorized"
]


def category_sort_key(c: str) -> int:
    try:
        return CATEGORY_ORDER.index(c)
    except ValueError:
        return len(CATEGORY_ORDER)


def emit_index(modules: list[dict], indent: str = "") -> str:
    """One-line-per-module index, grouped by category. Used for on-demand listing."""
    lines: list[str] = []
    by_cat: dict[str, list[dict]] = {}
    for m in modules:
        by_cat.setdefault(m["category"], []).append(m)
    for cat in sorted(by_cat.keys(), key=category_sort_key):
        lines.append(f"{indent}**{cat.title()}** ({len(by_cat[cat])}):")
        for m in by_cat[cat]:
            slash = f" `{m['slash_command']}`" if m["slash_command"] else ""
            d = short_description(m["description"])
            tier = tier_annotation(m.get("model", ""))
            tier_suffix = f" {tier}" if tier else ""
            lines.append(f"{indent}- `{m['slug']}`{slash} — {d}{tier_suffix}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ── Resolver ─────────────────────────────────────────────────────────────────
# One always-on artifact replacing N always-on descriptions. Its own description
# is the only standing cost; the catalog table in its body is read on the turns
# that actually need to route, and the module body itself on the turn after that.
RESOLVER_SLUG = "100x-resolver"
CATALOG_DIRNAME = "100xprism-catalog"

RESOLVER_DESCRIPTION = (
    "Catalog of specialist 100xprism workflows kept out of the always-on index — "
    "marketing, SEO, CRO, copywriting, growth, pricing, sales, design, accessibility, "
    "motion, and data-visualization playbooks. Read this file's table to find the right "
    "one, then read that module's SKILL.md path before starting the work."
)


def user_skills_mode() -> str:
    """How much of the catalog gets installed as real user-scope skills.

    'must' is the lean default. Set by `100xprism optimize`/`slim`, or per-run via
    PRISM_SKILLS. Unknown values fail closed to 'must' instead of widening context.
    """
    env = os.environ.get("PRISM_SKILLS", "").strip().lower()
    if env in ("all", "profile", "must"):
        return env
    if env:
        return "must"
    try:
        cfg = json.loads((Path.home() / ".100xprism" / "config.json").read_text())
    except (OSError, ValueError):
        return "must"
    mode = str(cfg.get("skills", "must")).strip().lower()
    return mode if mode in ("all", "profile", "must") else "must"


def split_by_mode(modules: list[dict], mode: str) -> tuple[list[dict], list[dict]]:
    """(installed, catalog) for a user-scope skills mode."""
    if mode == "all":
        return list(modules), []
    if mode == "must":
        keep = [m for m in modules if m["retention"] == "must"]
    else:  # profile
        keep = [m for m in modules if m["retention"] in ("must", "profile")]
    kept = {m["slug"] for m in keep}
    return keep, [m for m in modules if m["slug"] not in kept]


def render_catalog_table(catalog: list[dict], path_template: str) -> str:
    """Markdown table: one row per catalog module, grouped by category.

    `path_template` is formatted with `slug` and tells the agent exactly what to
    read — a row is only useful if it resolves to a file without further search.
    """
    if not catalog:
        return "_No catalog modules — every module is installed as a skill._\n"
    by_cat: dict[str, list[dict]] = {}
    for m in catalog:
        by_cat.setdefault(m["category"], []).append(m)
    lines: list[str] = []
    for cat in sorted(by_cat.keys(), key=category_sort_key):
        lines.append(f"\n### {cat.title()}\n")
        lines.append("| Module | Use it when | Read |")
        lines.append("|---|---|---|")
        for m in sorted(by_cat[cat], key=lambda x: x["slug"]):
            trigger = short_description(m["description"]).replace("|", "\\|")
            lines.append(f"| `{m['slug']}` | {trigger} | `{path_template.format(slug=m['slug'])}` |")
    return "\n".join(lines) + "\n"


def render_resolver(catalog: list[dict], path_template: str) -> str:
    """The resolver artifact's SKILL.md."""
    return (
        "---\n"
        f"name: {RESOLVER_SLUG}\n"
        f"description: {RESOLVER_DESCRIPTION}\n"
        "category: docs\n"
        "tier: on-demand\n"
        "---\n\n"
        f"# 100xprism catalog ({len(catalog)} modules)\n\n"
        "These modules are deliberately not in the always-on skill index. Find the row "
        "that matches the task, **read the file in its `Read` column**, then follow it as "
        "you would any skill. If nothing matches, proceed without one.\n"
        + render_catalog_table(catalog, path_template)
    )


def render_generic_route(argument_expr: str = "$ARGUMENTS") -> str:
    """One compact command/prompt replacing resident aliases for routed modules."""
    return (
        "---\n"
        "description: Load any routed 100xprism workflow by slug without indexing every workflow.\n"
        "argument-hint: <workflow> [arguments]\n"
        "---\n\n"
        f"{ALIAS_MARKER}\n\n"
        "Use the `100x-resolver` skill. Find the workflow named by the first argument, "
        "read its catalog SKILL.md path, and follow it with the remaining arguments.\n\n"
        f"{argument_expr}\n"
    )


CODEX_AGENTS_MARKER = "# Generated by 100xprism"
GENERATED_AGENTS_TITLES = ("# 100x Dev for Codex", "# 100x Dev for Pi")


def is_generated_agents(text: str) -> bool:
    """True only for our exact header: title line, then the marker line.

    A hand-written AGENTS.md that merely mentions the marker is not ours.
    """
    lines = text.splitlines()
    return (len(lines) >= 2 and lines[0].strip() in GENERATED_AGENTS_TITLES
            and lines[1].startswith(CODEX_AGENTS_MARKER))


def render_codex_agents(modules: list[dict]) -> str:
    """Compact Codex project guidance.

    Codex has a default AGENTS.md byte budget, while repo skills load through
    progressive disclosure. Keep AGENTS.md as routing/orientation text and emit
    full module bodies into .agents/skills instead.
    """
    out = [
        "# 100x Dev for Codex\n",
        "# Generated by 100xprism (https://github.com/rajitsaha/100xprism)\n",
        "# Source of truth: modules/<slug>/SKILL.md. Regenerate instead of hand-editing.\n\n",
        "## How Codex Should Use 100x Dev\n\n",
        "- Full reusable workflows live in `.agents/skills/<slug>/SKILL.md` so Codex can load them on demand.\n",
        "- When the user names a 100xprism slash workflow like `/gate`, treat it as a request to use the matching skill in `.agents/skills/`.\n",
        "- Prefer explicit skill invocation (`$gate`, `$commit`, `$test`, etc.) or `/skills` when available; custom prompt slash commands are intentionally not generated.\n",
        "- The generated `.agents/100x-index.md` contains the full module catalog when you need to browse available skills.\n",
        "- Codex hooks, when generated, live in `.codex/hooks.json`. Review and trust them with `/hooks` before expecting enforcement.\n",
        "- Claude Code plugins in `plugins/plugins.json` are not Codex plugins. Use Codex `/plugins` for Codex-native plugins and app/MCP integrations.\n\n",
        "## 100xprism Command Map\n\n",
    ]

    commands = [m for m in modules if m["slash_command"]]
    for m in sorted(commands, key=lambda x: x["slash_command"]):
        out.append(f"- `{m['slash_command']}` → `${m['slug']}` — {short_description(m['description'])}\n")

    return "".join(out)


def render_codex_index(modules: list[dict]) -> str:
    """Render the browseable module catalog outside Codex's always-loaded router."""
    return (
        "# 100xprism Skill Index\n\n"
        "Generated by 100xprism from `modules/<slug>/SKILL.md`. Full bodies are in "
        "`.agents/skills/<slug>/SKILL.md`; regenerate instead of hand-editing.\n\n"
        + emit_index(modules)
    )


def cmd_list():
    mods = list_modules()
    print(json.dumps(mods, indent=2))


def cmd_detect_profiles(project_dir: str):
    """Report the profiles a project looks like, for `100xprism slim`."""
    profiles = detect_profiles(project_dir)
    mods = list_modules()
    keep, catalog = select_modules(mods, profiles)
    print(json.dumps({
        "profiles": profiles,
        "installed": len(keep),
        "catalog": len(catalog),
    }, indent=2))


def _write_catalog_bodies(catalog: list[dict], catalog_dir: Path) -> None:
    """Park catalog module bodies on disk, outside anything the tool indexes.

    Cleared and rewritten wholesale: everything under this directory is ours, so
    a module that graduates back into the skill index leaves no stale copy behind.
    """
    if catalog_dir.exists():
        shutil.rmtree(catalog_dir)
    if not catalog:
        return
    catalog_dir.mkdir(parents=True, exist_ok=True)
    for m in catalog:
        target = catalog_dir / m["slug"]
        shutil.copytree(m["dir"], target)
        (target / GENERATED_MARKER).write_text(
            "Generated by 100xprism from modules/<slug>/SKILL.md. Regenerate instead of editing here.\n"
        )


def cmd_emit_cursor(project_dir: str):
    rules_dir = Path(project_dir) / ".cursor" / "rules"
    if rules_dir.exists():
        # Remove only files we previously wrote (those with our generation marker).
        # The marker sits on line 7 — after the 5-line frontmatter block and its
        # trailing blank — so the window must reach past it. It was 6 for a long
        # time, which silently matched nothing and orphaned every removed module's
        # rule. See test_cursor_prune_removes_real_generated_rule.
        for f in rules_dir.glob("*.mdc"):
            try:
                head = f.read_text().splitlines()[:CURSOR_MARKER_LINES]
                if any(CURSOR_MARKER in line for line in head):
                    f.unlink()
            except OSError:
                pass
    rules_dir.mkdir(parents=True, exist_ok=True)
    mods = list_modules()

    # Fresh emits are must-only. Explicit project profiles widen the index and
    # `profiles: ["all"]` restores the legacy unfiltered output.
    profiles = active_profiles(project_dir)
    keep, catalog = (mods, []) if profiles is None else select_modules(mods, profiles)

    def write_rule(slug: str, description: str, always_apply: str, model: str, body: str) -> None:
        cursor_fm = [
            "---",
            f"description: {description}",
            "globs:",
            f"alwaysApply: {always_apply}",
            "---",
            "",
            f"<!-- generated by 100xprism from modules/{slug}/SKILL.md -->",
            "",
        ]
        tier = tier_annotation(model)
        if tier:
            cursor_fm += [tier, ""]
        (rules_dir / f"{slug}.mdc").write_text("\n".join(cursor_fm) + body.lstrip("\n"))

    for m in keep:
        # Map tier to Cursor rule type: core modules are always in context;
        # on-demand modules are agent-requested via a tight first-sentence description.
        write_rule(
            m["slug"], short_description(m["description"]),
            "true" if m["tier"] == "core" else "false", m.get("model", ""), m["body"],
        )


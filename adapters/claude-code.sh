#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODULES_PY="$REPO_DIR/adapters/lib/modules.py"
CLAUDE_DIR="$HOME/.claude"
COMMANDS_DIR="$CLAUDE_DIR/commands"
SETTINGS_FILE="$CLAUDE_DIR/settings.json"

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# install_global — install all 100xprism modules into Claude Code.
# Each module becomes a skill at ~/.claude/skills/<slug>/SKILL.md.
# Modules with a slash_command also get an alias at ~/.claude/commands/<name>.md.
install_global() {
  echo ""
  echo "Installing modules for Claude Code..."

  if [ -d "$COMMANDS_DIR" ] && [ "$(ls -A "$COMMANDS_DIR" 2>/dev/null)" ]; then
    BACKUP="$CLAUDE_DIR/commands.bak.$(date +%Y%m%d_%H%M%S)"
    cp -r "$COMMANDS_DIR" "$BACKUP"
    echo -e "  ${YELLOW}→ Backed up existing commands to $(basename "$BACKUP")${NC}"
    # Keep the 3 newest backups; every run makes one, so they pile up otherwise.
    ls -1dt "$CLAUDE_DIR"/commands.bak.* 2>/dev/null | tail -n +4 | while IFS= read -r old; do rm -rf "$old"; done
  fi

  python3 "$MODULES_PY" emit-claude-code

  echo -e "  ${GREEN}→ Modules installed to ~/.claude/skills/ + slash aliases in ~/.claude/commands/ ✓${NC}"
  echo -e "  ${CYAN}→ Restart Claude Code to load new modules${NC}"
}

install_project() {
  local project_path="${1:-.}"
  local instruction_file=""

  for f in CLAUDE.md AGENTS.md .cursorrules; do
    if [ -f "$project_path/$f" ]; then
      instruction_file="$project_path/$f"
      break
    fi
  done

  if [ -n "$instruction_file" ]; then
    echo -e "  ${CYAN}→ Instruction file already exists: $instruction_file (skipping scaffold)${NC}"
    return
  fi

  local target="$project_path/CLAUDE.md"
  local project_name
  project_name="$(basename "$(cd "$project_path" && pwd)")"

  # CLAUDE.md is re-sent on every turn, so it holds only what a model cannot infer
  # from the code: project facts, non-obvious invariants, and a router to the docs
  # that carry the detail. Machine-readable config moved to .claude/100xprism.yml,
  # which the modules that need it read on demand.
  cat > "$target" << SCAFFOLD
# $project_name — Project Instructions

<!-- Generated by 100xprism. Every line here is re-sent on EVERY turn — keep it to
     facts a model cannot infer from the code, and push detail into docs/ below. -->

## Project Overview

<!-- Stack, hosting, database, auth — one bullet each. -->
- TODO

## Key Conventions

<!-- Non-obvious invariants ONLY: the things that cost a debugging session when
     guessed wrong (ID types, middleware ordering, enum/name mismatches, and so on).
     Anything a competent model would already do correctly does not belong here. -->
- TODO

## Reference docs (read on demand)

<!-- The router. Add a row per area; the agent reads the doc only when it applies,
     so detail here is free. Delete the placeholder rows you do not need. -->

| When you are… | Read |
|---|---|
| writing or running tests | \`docs/testing.md\` |
| reasoning about services, data flow, layout | \`docs/architecture.md\` |
| bumping deps / triaging security findings | \`docs/security-exceptions.md\` |

## Rules

<!-- Project-specific rules for Claude. /update-claude appends to this section. -->
SCAFFOLD

  mkdir -p "$project_path/.claude"
  local config="$project_path/.claude/100xprism.yml"
  if [ ! -f "$config" ]; then
    cat > "$config" << 'PRISMCONFIG'
# 100xprism project config — read on demand, NOT loaded into every turn.
# Consumed by /db, /query, /gate, /cloud-security and /launch.
# Everything is optional; delete what does not apply.
#
# Keys must stay flush-left (column 0): the modules match them with an anchored
# grep, so an indented key is silently invisible.

# --- Database (/db, /query) ---
# engine: postgres          # postgres | mysql | sqlite | snowflake | bigquery
#                           # | athena | databricks | presto | oracle | cloud-sql
# connection: default
# connections:
#   default:
#     host: localhost
#     port: 5432
#     name: mydb
#     user: myuser
#     auth: env:DB_PASSWORD   # env:VAR_NAME | secret:SECRET_NAME | prompt

# --- Cloud / GCP (/gate, /cloud-security, /launch) ---
# gcp_project: my-gcp-project
# cloud_run_service: my-service
# region: us-central1

# --- Production (/launch, /push) ---
# production_url: https://example.com
# health_url: https://example.com/health

# --- Known findings /security should skip ---
# security_exceptions:
#   - CVE-2023-XXXX: false positive in test dependency
PRISMCONFIG
  fi

  echo -e "  ${GREEN}→ Scaffolded CLAUDE.md + .claude/100xprism.yml in $project_path ✓${NC}"
  echo -e "  ${YELLOW}→ Fill in Project Overview / Key Conventions; put db/cloud config in .claude/100xprism.yml${NC}"
}

check_bun() {
  if ! command -v bun &>/dev/null; then
    echo ""
    echo -e "  ${YELLOW}⚠ Bun is required by the claude-mem plugin but is not installed.${NC}"
    echo ""
    read -rp "  Install Bun now? (recommended) [Y/n]: " install_bun
    install_bun="${install_bun:-Y}"
    if [[ "$install_bun" =~ ^[Yy]$ ]]; then
      echo "  Installing Bun..."
      curl -fsSL https://bun.sh/install | bash
      export BUN_INSTALL="$HOME/.bun"
      export PATH="$BUN_INSTALL/bin:$PATH"
      if command -v bun &>/dev/null; then
        echo -e "  ${GREEN}→ Bun installed ✓${NC}"
      else
        echo -e "  ${YELLOW}→ Bun installed — restart your terminal to activate it${NC}"
      fi
    else
      echo -e "  ${YELLOW}→ Skipping Bun install. claude-mem hooks will show errors until Bun is available.${NC}"
    fi
  fi
}

install_plugins() {
  echo ""
  echo "Installing plugins for Claude Code..."
  mkdir -p "$CLAUDE_DIR"

  check_bun

  PLUGINS_FILE="$REPO_DIR/plugins/plugins.json"

  if [ ! -f "$SETTINGS_FILE" ]; then
    echo '{}' > "$SETTINGS_FILE"
  fi

  # Reconcile plugins (adds new, removes 100xprism-managed plugins dropped from
  # plugins.json) — the same helper the update path uses, so install and update
  # stay in agreement.
  python3 "$REPO_DIR/adapters/lib/sync_plugins.py" \
    --settings "$SETTINGS_FILE" --plugins "$PLUGINS_FILE"

  # Re-apply opted-in packs and prune any dropped from packs.json.
  python3 "$REPO_DIR/adapters/lib/packs.py" sync --settings "$SETTINGS_FILE" || \
    echo -e "  ${YELLOW}→ Pack sync failed — run /pack to check pack state${NC}"

  echo -e "  ${GREEN}→ Plugins merged into ~/.claude/settings.json ✓${NC}"
  echo -e "  ${CYAN}→ Restart Claude Code to activate new plugins${NC}"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  case "${1:-}" in
    --plugins) install_plugins ;;
    *) install_global ;;
  esac
fi

'use strict'

// Ownership-proven cleanup shared by install (Windows emitter), uninstall, and
// `audit --fix`. Every removal here requires proof that 100xprism wrote the file:
// a generated marker, a manifest entry, a managed hook path, or an exact v1 header
// signature. Anything without proof is left alone.
//
// The marker constants mirror adapters/lib/modules.py; test/cleanup-contract.test.js
// checks the two stay equal.

const fs = require('fs')
const path = require('path')

const GENERATED_MARKER = '.100xprism-generated'
const ALIAS_MARKER = '<!-- 100xprism generated alias — regenerate, do not edit -->'
const MANIFEST_NAME = '.100xprism-manifest.json'
const CURSOR_MARKER = 'generated by 100xprism'
const CURSOR_MARKER_LINES = 10
const CODEX_AGENTS_MARKER = '# Generated by 100xprism'
const GENERATED_AGENTS_TITLES = ['# 100x Dev for Codex', '# 100x Dev for Pi']
const CODEX_HOOK_RUNNER = '.codex/100xprism-hooks/'
const RESOLVER_SLUG = '100x-resolver'
const CATALOG_DIRNAME = '100xprism-catalog'
const MANAGED_HOOK_PATH = '/100xprism/hooks/'
const LEGACY_V1_COMMANDS = path.join(__dirname, '..', 'adapters', 'lib', 'legacy-v1-commands.json')

function readText(file) {
  try { return fs.readFileSync(file, 'utf8') } catch { return null }
}

function readJson(file, fallback) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')) } catch { return fallback }
}

function firstLine(file) {
  const text = readText(file)
  if (text === null) return ''
  const line = text.split(/\r?\n/).find(l => l.trim())
  return line ? line.trim() : ''
}

function rm(target) {
  fs.rmSync(target, { recursive: true, force: true })
}

function isDir(p) {
  try { return fs.statSync(p).isDirectory() } catch { return false }
}

// ── v1 leftovers ────────────────────────────────────────────────────────────

function legacyV1Matches(commandsDir) {
  const signatures = (readJson(LEGACY_V1_COMMANDS, {}) || {}).files || {}
  const out = []
  for (const [rel, headers] of Object.entries(signatures)) {
    const file = path.join(commandsDir, ...rel.split('/'))
    if (fs.existsSync(file) && headers.includes(firstLine(file))) out.push(file)
  }
  return out
}

function sweepLegacyV1Commands(commandsDir) {
  const matches = legacyV1Matches(commandsDir)
  for (const file of matches) rm(file)
  const engines = path.join(commandsDir, 'db-engines')
  if (isDir(engines) && fs.readdirSync(engines).length === 0) fs.rmdirSync(engines)
  return matches.length
}

// ── settings.json hooks ─────────────────────────────────────────────────────

function isManagedHookCommand(command) {
  return String(command || '').replace(/\\/g, '/').includes(MANAGED_HOOK_PATH)
}

// Path of the script a managed hook runs, e.g. python3 "/x/100xprism/hooks/a.py".
function hookScriptPath(command) {
  const m = String(command || '').match(/"([^"]+\.py)"|(\S+\.py)/)
  return m ? (m[1] || m[2]) : null
}

// Removes managed hook commands (every event) for which `shouldRemove` is true.
function filterManagedHooks(settingsFile, shouldRemove) {
  const settings = readJson(settingsFile, null)
  if (!settings || typeof settings !== 'object' || !settings.hooks) return 0
  let removed = 0
  for (const [event, entries] of Object.entries(settings.hooks)) {
    if (!Array.isArray(entries)) continue
    const kept = []
    for (const entry of entries) {
      const hooks = Array.isArray(entry && entry.hooks) ? entry.hooks : []
      const keptHooks = hooks.filter(h => {
        const drop = isManagedHookCommand(h && h.command) && shouldRemove(h.command)
        if (drop) removed++
        return !drop
      })
      if (keptHooks.length) kept.push({ ...entry, hooks: keptHooks })
      else if (!hooks.length) kept.push(entry)
    }
    if (kept.length) settings.hooks[event] = kept
    else delete settings.hooks[event]
  }
  if (!Object.keys(settings.hooks).length) delete settings.hooks
  if (removed) fs.writeFileSync(settingsFile, JSON.stringify(settings, null, 2))
  return removed
}

function removeManagedHooks(settingsFile) {
  return filterManagedHooks(settingsFile, () => true)
}

function brokenManagedHooks(settingsFile) {
  const settings = readJson(settingsFile, null)
  const out = []
  for (const entries of Object.values((settings && settings.hooks) || {})) {
    for (const entry of Array.isArray(entries) ? entries : []) {
      for (const h of (entry && entry.hooks) || []) {
        if (!isManagedHookCommand(h && h.command)) continue
        const script = hookScriptPath(h.command)
        if (script && !fs.existsSync(script)) out.push(h.command)
      }
    }
  }
  return out
}

// Managed hooks whose script lives under `dir` (e.g. a package about to be deleted).
function removeManagedHooksUnder(settingsFile, dir) {
  const prefix = path.resolve(dir).replace(/\\/g, '/') + '/'
  return filterManagedHooks(settingsFile, command => {
    const script = hookScriptPath(command)
    return Boolean(script) && path.resolve(script).replace(/\\/g, '/').startsWith(prefix)
  })
}

function removeBrokenManagedHooks(settingsFile) {
  return filterManagedHooks(settingsFile, command => {
    const script = hookScriptPath(command)
    return Boolean(script) && !fs.existsSync(script)
  })
}

// ── generated skills / aliases ──────────────────────────────────────────────

// Skill dirs carrying our marker (or listed in our manifest), then the manifest.
function removeGeneratedSkills(skillsDir) {
  if (!isDir(skillsDir)) return 0
  const manifest = readJson(path.join(skillsDir, MANIFEST_NAME), {}) || {}
  const listed = new Set(manifest.skills || [])
  let removed = 0
  for (const name of fs.readdirSync(skillsDir)) {
    const dir = path.join(skillsDir, name)
    if (!isDir(dir)) continue
    if (fs.existsSync(path.join(dir, GENERATED_MARKER)) || listed.has(name)) {
      rm(dir)
      removed++
    }
  }
  rm(path.join(skillsDir, MANIFEST_NAME))
  return removed
}

function removeGeneratedAliases(commandsDir) {
  if (!isDir(commandsDir)) return 0
  let removed = 0
  for (const name of fs.readdirSync(commandsDir)) {
    const file = path.join(commandsDir, name)
    if (!name.endsWith('.md') || isDir(file)) continue
    const text = readText(file)
    if (text && text.includes(ALIAS_MARKER)) {
      rm(file)
      removed++
    }
  }
  return removed
}

// ── project-scope artifacts ─────────────────────────────────────────────────

function hasCursorMarker(file) {
  const text = readText(file)
  return text !== null &&
    text.split(/\r?\n/).slice(0, CURSOR_MARKER_LINES).some(l => l.includes(CURSOR_MARKER))
}

// True only for our exact header: title line, then the marker line. A
// hand-written AGENTS.md that merely mentions the marker is not ours.
function isGeneratedAgents(text) {
  if (typeof text !== 'string') return false
  const lines = text.split(/\r?\n/)
  return lines.length >= 2 && GENERATED_AGENTS_TITLES.includes(lines[0].trim()) &&
    lines[1].startsWith(CODEX_AGENTS_MARKER)
}

// Drop every hook that calls our Codex runner (even inside a group a user added
// to), then any group left empty; delete the file only when nothing else is left.
function removeCodexHooks(hooksFile) {
  const data = readJson(hooksFile, null)
  if (!data || typeof data !== 'object' || Array.isArray(data)) return 0
  const events = data.hooks
  if (!events || typeof events !== 'object' || Array.isArray(events)) return 0
  const ours = h => String((h && h.command) || '').includes(CODEX_HOOK_RUNNER)
  let removed = 0
  for (const [event, groups] of Object.entries(events)) {
    if (!Array.isArray(groups)) continue
    const kept = []
    for (const group of groups) {
      if (!Array.isArray(group && group.hooks)) { kept.push(group); continue }
      const hooks = group.hooks.filter(h => !ours(h))
      removed += group.hooks.length - hooks.length
      if (hooks.length === group.hooks.length) kept.push(group)
      else if (hooks.length) kept.push({ ...group, hooks })
    }
    if (kept.length) events[event] = kept
    else delete events[event]
  }
  const otherKeys = Object.keys(data).filter(k => k !== 'hooks')
  if (!Object.keys(events).length && !otherKeys.length) rm(hooksFile)
  else if (removed) fs.writeFileSync(hooksFile, JSON.stringify(data, null, 2) + '\n')
  return removed
}

function cleanProject(projectDir) {
  let removed = 0
  const count = target => { if (fs.existsSync(target)) { rm(target); removed++ } }

  const rulesDir = path.join(projectDir, '.cursor', 'rules')
  if (isDir(rulesDir)) {
    for (const name of fs.readdirSync(rulesDir)) {
      const file = path.join(rulesDir, name)
      if (name.endsWith('.mdc') && hasCursorMarker(file)) count(file)
    }
  }
  count(path.join(projectDir, '.cursor', CATALOG_DIRNAME))

  for (const base of ['.agents', '.pi']) {
    removed += removeGeneratedSkills(path.join(projectDir, base, 'skills'))
    count(path.join(projectDir, base, CATALOG_DIRNAME))
  }
  count(path.join(projectDir, '.agents', '100x-index.md'))
  count(path.join(projectDir, '.pi', '.100xprism-pi-manifest.json'))
  const codexHooks = path.join(projectDir, '.codex', 'hooks.json')
  if (fs.existsSync(codexHooks) && removeCodexHooks(codexHooks)) removed++
  count(path.join(projectDir, '.codex', '100xprism-hooks'))

  const agents = path.join(projectDir, 'AGENTS.md')
  if (isGeneratedAgents(readText(agents))) count(agents)
  return removed
}

